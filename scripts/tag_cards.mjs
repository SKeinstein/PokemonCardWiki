function applyAttackFacets(tags, { facets, shelf }) {
  for (const f of facets) tags.add(FACET_LABELS[f]);
  for (const g of shelf) {
    tags.add('ダメージ修飾');
    tags.add(FACET_LABELS[g]);
  }
}

